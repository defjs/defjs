const rank = new Map<string, number>(
  apiOrder.map((identity, index) => [identity, index]),
);

export function compareApiIdentity(left: string, right: string): number {
  const leftRank = rank.get(left) ?? apiOrder.length;
  const rightRank = rank.get(right) ?? apiOrder.length;
  if (leftRank !== rightRank) return leftRank - rightRank;
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}
